/// The first line of every tool-managed file.
const HEADER: &str = "# generated by hali; edit with the CLI\n";

/// The files in the data dir. `extensions.ttl` is read-only to hali, so it is not here.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum File {
    Vocabulary,
    Resources,
}

impl File {
    fn name(self) -> &'static str {
        match self {
            File::Vocabulary => "vocabulary.ttl",
            File::Resources => "resources.ttl",
        }
    }

    /// The named graph this file is loaded into.
    pub fn graph(self) -> NamedNode {
        match self {
            File::Vocabulary => graph("vocabulary"),
            File::Resources => graph("resources"),
        }
    }
}

/// The named graph of the embedded core ontology and shapes.
pub const CORE_GRAPH: &str = "https://w3id.org/hali/graph/core";

/// The named graph of the hand-written `extensions.ttl`.
pub const EXTENSIONS_GRAPH: &str = "https://w3id.org/hali/graph/extensions";

fn graph(name: &str) -> NamedNode {
    NamedNode::new_unchecked(format!("https://w3id.org/hali/graph/{name}"))
}

#[derive(Debug)]
pub enum Error {
    /// A path could not be read, created or written.
    Io { path: PathBuf },
    /// A Turtle file is not valid Turtle. `line` and `column` start at 1.
    Unparseable {
        file: String,
        line: u64,
        column: u64,
    },
    /// The store lock `path` (`<data dir>/.lock`) was not got, or the store changed under it.
    Locked { path: PathBuf, reason: LockReason },
    /// The data dir is someone else's, or group- or world-writable (`dir_problem`).
    UnsafeDir { path: PathBuf, reason: &'static str },
}

/// Why a lock attempt failed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LockReason {
    /// Another process held the lock for the whole 5 s wait.
    Timeout,
    /// The data dir was absent at first, and a store file appeared before this writer locked.
    Changed,
}

/// Loads the embedded core ontology and shapes, and the files in `dir`, under a shared lock on
/// `<dir>/.lock` held only while loading (spec §3.3). A missing dir or file is an empty graph, a
/// missing `.lock` is read without a lock, and nothing is created.
pub fn load(dir: &Path) -> Result<Store, Error> {
    let _shared = lock::shared(dir)?;
    store_file::load_files(dir)
}

/// Parses Turtle into one named graph. On a syntax error, returns its 1-based line and column.
fn parse_into(store: &Store, bytes: &[u8], graph: GraphNameRef<'_>) -> Result<(), (u64, u64)> {
    if let Err(e) = std::str::from_utf8(bytes) {
        return Err(position_of(bytes, e.valid_up_to()));
    }
    for triple in TurtleParser::new().for_slice(bytes) {
        let triple = triple.map_err(|e| {
            let start = e.location().start;
            (start.line + 1, start.column + 1)
        })?;
        store
            .insert(triple.as_ref().in_graph(graph))
            .expect("inserting into the in-memory store");
    }
    Ok(())
}

/// The 1-based line and column (in code points) of a byte offset into `bytes`.
fn position_of(bytes: &[u8], offset: usize) -> (u64, u64) {
    let before = String::from_utf8_lossy(&bytes[..offset]);
    let line = before.matches('\n').count() as u64 + 1;
    let column = before.rsplit('\n').next().unwrap_or("").chars().count() as u64 + 1;
    (line, column)
}

/// Serializes one file's graph as deterministic Turtle (spec §3.4): the header line, the fixed
/// prefix table, then the triples sorted by subject, predicate and object (N-Triples forms),
/// with `rdf:type` first per subject.
pub fn to_turtle(store: &Store, file: File) -> String {
    let graph = file.graph();
    let triples: Vec<Triple> = store
        .quads_for_pattern(None, None, None, Some(graph.as_ref().into()))
        .map(|q| Triple::from(q.expect("reading the in-memory store")))
        .collect();
    let mut out = String::from(HEADER);
    out.push_str(&turtle_document(triples, |_| false));
    out
}

/// Serializes triples as the Turtle of `to_turtle` without its header line (spec §3.4, §9.9): the
/// fixed prefix table, then the triples sorted and grouped. Every character for which `escape`
/// is true is written as a Turtle `\uXXXX` or `\UXXXXXXXX` escape, and an IRI that holds one is
/// written whole, never as a prefixed name. A blank node label that holds one, or that is not a
/// Turtle `BLANK_NODE_LABEL` (such as one with `:`, which `BNODE` can make), gets a new label,
/// since a label cannot carry an escape. The caller keeps layout characters (LF, TAB) out of
/// `escape`.
pub fn turtle_document(mut triples: Vec<Triple>, escape: impl Fn(char) -> bool) -> String {
    triples.sort_by_cached_key(|t| {
        (
            t.subject.to_string(),
            t.predicate != rdf::TYPE,
            t.predicate.to_string(),
            t.object.to_string(),
        )
    });

    // An IRI with a character to escape is serialized as a stand-in that no prefix can shorten,
    // then put back whole in angle brackets. A blank node label cannot hold an escape, so a label
    // with such a character, or one Turtle's grammar rejects, is replaced by a safe one. Both
    // reach into triple terms.
    let marker = stand_in_marker(&triples);
    let needs_relabel = |label: &str| label.chars().any(&escape) || !is_turtle_label(label);
    let relabel_prefix = relabel_prefix(&triples, &needs_relabel);
    let mut stand_ins: Vec<String> = Vec::new();
    let mut stand_in = |iri: NamedNode| {
        if !iri.as_str().chars().any(&escape) {
            return iri;
        }
        stand_ins.push(iri.into_string());
        NamedNode::new_unchecked(format!("{marker}{}", stand_ins.len() - 1))
    };
    let relabel = |b: BlankNode| match &relabel_prefix {
        Some(prefix) if needs_relabel(b.as_str()) => {
            let hex: String = b.as_str().bytes().map(|x| format!("{x:02x}")).collect();
            BlankNode::new_unchecked(format!("{prefix}{hex}"))
        }
        _ => b,
    };
    let triples: Vec<Triple> = triples
        .into_iter()
        .map(|t| safe_triple(t, &mut stand_in, &relabel))
        .collect();

    // oxttl orders its prefix lines by namespace length, so hali writes the prelude itself
    // and keeps the serializer's prefixes only for abbreviation.
    let mut serializer = TurtleSerializer::new();
    for (name, iri) in PREFIXES {
        serializer = serializer
            .with_prefix(name, iri)
            .expect("the prefix table is valid");
    }
    let mut writer = serializer.for_writer(Vec::new());
    for triple in &triples {
        writer
            .serialize_triple(triple)
            .expect("writing to memory cannot fail");
    }
    let body = String::from_utf8(writer.finish().expect("writing to memory cannot fail"))
        .expect("oxttl writes UTF-8");
    let prelude_lines = if triples.is_empty() {
        0
    } else {
        PREFIXES.len()
    };
    let mut body: String = body
        .split_inclusive('\n')
        .skip(prelude_lines)
        .collect::<String>();
    for (n, iri) in stand_ins.iter().enumerate() {
        body = body.replace(&format!("<{marker}{n}>"), &format!("<{iri}>"));
    }

    let mut out = String::new();
    for (name, iri) in PREFIXES {
        out.push_str(&format!("@prefix {name}: <{iri}> .\n"));
    }
    out.push('\n');
    out.push_str(&body);
    escape_turtle(&out, &escape)
}

/// `t` with every IRI passed through `stand_in` and every blank node through `relabel`, triple
/// terms included.
fn safe_triple(
    t: Triple,
    stand_in: &mut impl FnMut(NamedNode) -> NamedNode,
    relabel: &impl Fn(BlankNode) -> BlankNode,
) -> Triple {
    let subject = match t.subject {
        NamedOrBlankNode::NamedNode(n) => NamedOrBlankNode::NamedNode(stand_in(n)),
        NamedOrBlankNode::BlankNode(b) => NamedOrBlankNode::BlankNode(relabel(b)),
    };
    let predicate = stand_in(t.predicate);
    let object = match t.object {
        Term::NamedNode(n) => Term::NamedNode(stand_in(n)),
        Term::BlankNode(b) => Term::BlankNode(relabel(b)),
        Term::Literal(l) if l.language().is_none() => {
            let datatype = stand_in(l.datatype().into_owned());
            Term::Literal(Literal::new_typed_literal(l.value(), datatype))
        }
        Term::Literal(l) => Term::Literal(l),
        Term::Triple(inner) => Term::Triple(Box::new(safe_triple(*inner, stand_in, relabel))),
    };
    Triple::new(subject, predicate, object)
}

/// When a blank node label of `triples` needs a new label, a prefix that no label starts with:
/// such a label becomes the prefix and the hex of its UTF-8 bytes, which is deterministic for
/// the same data and never equal to another label.
fn relabel_prefix(triples: &[Triple], needs_relabel: &impl Fn(&str) -> bool) -> Option<String> {
    fn labels(t: &Triple, out: &mut Vec<String>) {
        if let NamedOrBlankNode::BlankNode(b) = &t.subject {
            out.push(b.as_str().to_string());
        }
        match &t.object {
            Term::BlankNode(b) => out.push(b.as_str().to_string()),
            Term::Triple(inner) => labels(inner, out),
            _ => {}
        }
    }
    let mut all = Vec::new();
    for t in triples {
        labels(t, &mut all);
    }
    if !all.iter().any(|l| needs_relabel(l)) {
        return None;
    }
    let mut salt = 0;
    loop {
        let prefix = format!("h{salt}x");
        if !all.iter().any(|l| l.starts_with(&prefix)) {
            return Some(prefix);
        }
        salt += 1;
    }
}

/// Whether `label` matches Turtle's `BLANK_NODE_LABEL` after `_:`:
/// `(PN_CHARS_U | [0-9]) ((PN_CHARS | '.')* PN_CHARS)?`.
fn is_turtle_label(label: &str) -> bool {
    fn pn_chars_base(c: char) -> bool {
        matches!(c,
            'A'..='Z' | 'a'..='z'
            | '\u{C0}'..='\u{D6}' | '\u{D8}'..='\u{F6}' | '\u{F8}'..='\u{2FF}'
            | '\u{370}'..='\u{37D}' | '\u{37F}'..='\u{1FFF}' | '\u{200C}'..='\u{200D}'
            | '\u{2070}'..='\u{218F}' | '\u{2C00}'..='\u{2FEF}' | '\u{3001}'..='\u{D7FF}'
            | '\u{F900}'..='\u{FDCF}' | '\u{FDF0}'..='\u{FFFD}' | '\u{10000}'..='\u{EFFFF}')
    }
    fn pn_chars(c: char) -> bool {
        pn_chars_base(c)
            || matches!(c, '_' | '-' | '0'..='9' | '\u{B7}' | '\u{300}'..='\u{36F}' | '\u{203F}'..='\u{2040}')
    }
    let mut chars = label.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(pn_chars_base(first) || first == '_' || first.is_ascii_digit()) {
        return false;
    }
    let rest: Vec<char> = chars.collect();
    rest.iter().all(|&c| pn_chars(c) || c == '.') && rest.last().is_none_or(|&c| pn_chars(c))
}

/// A stand-in IRI prefix that no term of `triples` contains.
fn stand_in_marker(triples: &[Triple]) -> String {
    let mut salt = 0;
    loop {
        let marker = format!("urn:hali-stand-in-{salt}-");
        if !triples.iter().any(|t| t.to_string().contains(&marker)) {
            return marker;
        }
        salt += 1;
    }
}

/// Writes every character `escape` selects as a Turtle `\u` or `\U` escape.
fn escape_turtle(text: &str, escape: &impl Fn(char) -> bool) -> String {
    use std::fmt::Write;
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        let n = u32::from(c);
        if !escape(c) {
            out.push(c);
        } else if n <= 0xFFFF {
            write!(out, "\\u{n:04X}").expect("writing to a String");
        } else {
            write!(out, "\\U{n:08X}").expect("writing to a String");
        }
    }
    out
}

/// Reads a text file, if it exists.
pub fn read_text(path: &Path) -> Result<Option<String>, Error> {
    match fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(e) if e.kind() == ErrorKind::NotFound => Ok(None),
        Err(_) => Err(Error::Io {
            path: path.to_path_buf(),
        }),
    }
}

/// What `inspect` learns about a file to catalog, all from one open file descriptor.
#[derive(Debug)]
pub struct Inspected {
    pub byte_size: u64,
    /// The mtime, in whole seconds since the Unix epoch.
    pub mtime: i64,
    /// The SHA-256 of the content, lowercase hex.
    pub sha256: String,
    /// The first bytes of the content (at most `media_type::HEAD_LEN`).
    pub head: Vec<u8>,
}

/// Why a file cannot be cataloged.
#[derive(Debug, PartialEq)]
pub enum InspectError {
    Missing,
    Directory,
    /// Neither a regular file nor a directory: a FIFO, socket, device or symlink.
    Other,
    /// It exists but cannot be opened or read.
    Unreadable,
    /// It holds more bytes than the limit of `inspect_bounded`.
    TooLarge,
}

/// Opens the regular file at the real path `path` once, read-only and non-blocking, checks on
/// that descriptor that it is still a regular file, then hashes it by streaming. Nothing is
/// ever written to it.
pub fn inspect(path: &Path) -> Result<Inspected, InspectError> {
    inspect_upto(path, None)
}

/// `inspect`, reading at most `limit + 1` bytes: a file that holds more than `limit` bytes (by
/// its size on the open descriptor, or by what is read, should it grow) is `TooLarge`. The other
/// errors are `inspect`'s and come first.
pub fn inspect_bounded(path: &Path, limit: u64) -> Result<Inspected, InspectError> {
    inspect_upto(path, Some(limit))
}

fn inspect_upto(path: &Path, limit: Option<u64>) -> Result<Inspected, InspectError> {
    use sha2::{Digest, Sha256};
    use std::io::Read;
    use std::os::unix::fs::{MetadataExt, OpenOptionsExt};

    // A first look without opening, so a device or FIFO is never opened.
    kind(fs::symlink_metadata(path))?;
    // O_NONBLOCK: a FIFO swapped in after that look cannot block the open. O_NOFOLLOW: nor can a
    // symlink be followed. O_NOCTTY: a terminal never becomes the controlling one.
    let mut file = fs::OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NONBLOCK | libc::O_NOFOLLOW | libc::O_NOCTTY)
        .open(path)
        .map_err(|e| match e.kind() {
            ErrorKind::NotFound => InspectError::Missing,
            _ => InspectError::Unreadable,
        })?;
    let meta = kind(file.metadata())?;
    if limit.is_some_and(|limit| meta.len() > limit) {
        return Err(InspectError::TooLarge);
    }
    // Without a limit the read is unbounded; with one it stops one byte past it.
    let mut reader = (&mut file).take(limit.map_or(u64::MAX, |l| l.saturating_add(1)));

    let mut hasher = Sha256::new();
    let mut head = Vec::new();
    let mut buf = vec![0u8; 64 * 1024];
    let mut byte_size = 0u64;
    loop {
        let n = match reader.read(&mut buf) {
            Ok(0) => break,
            Ok(n) => n,
            Err(e) if e.kind() == ErrorKind::Interrupted => continue,
            Err(_) => return Err(InspectError::Unreadable),
        };
        hasher.update(&buf[..n]);
        let room = crate::media_type::HEAD_LEN.saturating_sub(head.len());
        head.extend_from_slice(&buf[..n.min(room)]);
        byte_size += n as u64;
    }
    if limit.is_some_and(|limit| byte_size > limit) {
        return Err(InspectError::TooLarge);
    }
    let sha256 = hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    Ok(Inspected {
        byte_size,
        mtime: meta.mtime(),
        sha256,
        head,
    })
}

/// A regular file's metadata, or the kind of thing that is there instead.
fn kind(meta: std::io::Result<fs::Metadata>) -> Result<fs::Metadata, InspectError> {
    match meta {
        Ok(m) if m.is_file() => Ok(m),
        Ok(m) if m.is_dir() => Err(InspectError::Directory),
        Ok(_) => Err(InspectError::Other),
        Err(e) if e.kind() == ErrorKind::NotFound => Err(InspectError::Missing),
        Err(_) => Err(InspectError::Unreadable),
    }
}

/// The size and mtime (whole seconds since the Unix epoch) of the regular file at `path`, from
/// `stat` only; `None` if there is no regular file there.
pub fn stat(path: &Path) -> Option<(u64, i64)> {
    use std::os::unix::fs::MetadataExt;
    fs::metadata(path)
        .ok()
        .filter(fs::Metadata::is_file)
        .map(|m| (m.len(), m.mtime()))
}
