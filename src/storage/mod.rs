//! The `storage` seam: Turtle files in the data dir <-> an in-memory store (spec §3).
//!
//! Each source sits in its own named graph, `https://w3id.org/hali/graph/{name}`; nothing is
//! put in the default graph.
//!
//! It also reads cataloged files (`inspect`, `stat`), only ever read-only.

use crate::ontology::{CORE_TTL, PREFIXES, SHAPES_TTL};
use oxigraph::model::vocab::rdf;
use oxigraph::model::{GraphNameRef, NamedNode, Triple};
use oxttl::{TurtleParser, TurtleSerializer};
use std::fs;
use std::io::ErrorKind;
use std::os::unix::fs::DirBuilderExt;
use std::path::{Path, PathBuf};

pub use oxigraph::store::Store;

/// The first line of every tool-managed file.
const HEADER: &str = "# generated by hali; edit with the CLI\n";

/// The files in the data dir. `extensions.ttl` is read-only to hali, so it is not here.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum File {
    Vocabulary,
    Resources,
}

impl File {
    fn name(self) -> &'static str {
        match self {
            File::Vocabulary => "vocabulary.ttl",
            File::Resources => "resources.ttl",
        }
    }

    /// The named graph this file is loaded into.
    pub fn graph(self) -> NamedNode {
        match self {
            File::Vocabulary => graph("vocabulary"),
            File::Resources => graph("resources"),
        }
    }
}

/// The named graph of the embedded core ontology and shapes.
pub const CORE_GRAPH: &str = "https://w3id.org/hali/graph/core";

/// The named graph of the hand-written `extensions.ttl`.
pub const EXTENSIONS_GRAPH: &str = "https://w3id.org/hali/graph/extensions";

fn graph(name: &str) -> NamedNode {
    NamedNode::new_unchecked(format!("https://w3id.org/hali/graph/{name}"))
}

#[derive(Debug)]
pub enum Error {
    /// A path could not be read, created or written.
    Io { path: PathBuf },
    /// A Turtle file is not valid Turtle. `line` and `column` start at 1.
    Unparseable {
        file: String,
        line: u64,
        column: u64,
    },
}

/// Loads the embedded core ontology and shapes, and the files in `dir`. A missing dir or file
/// is an empty graph; nothing is created.
pub fn load(dir: &Path) -> Result<Store, Error> {
    let io = |path: &Path| Error::Io {
        path: path.to_path_buf(),
    };
    let store = Store::new().map_err(|_| io(dir))?;
    for core in [CORE_TTL, SHAPES_TTL] {
        parse_into(&store, core.as_bytes(), graph("core").as_ref().into())
            .expect("the embedded core ontology and shapes are valid Turtle");
    }

    match fs::metadata(dir) {
        Err(e) if e.kind() == ErrorKind::NotFound => return Ok(store),
        Err(_) => return Err(io(dir)),
        Ok(meta) if !meta.is_dir() => return Err(io(dir)),
        Ok(_) => {}
    }
    for name in ["vocabulary", "resources", "extensions"] {
        let file = format!("{name}.ttl");
        let path = dir.join(&file);
        let bytes = match fs::read(&path) {
            Ok(bytes) => bytes,
            Err(e) if e.kind() == ErrorKind::NotFound => continue,
            Err(_) => return Err(io(&path)),
        };
        parse_into(&store, &bytes, graph(name).as_ref().into())
            .map_err(|(line, column)| Error::Unparseable { file, line, column })?;
    }
    Ok(store)
}

/// Parses Turtle into one named graph. On a syntax error, returns its 1-based line and column.
fn parse_into(store: &Store, bytes: &[u8], graph: GraphNameRef<'_>) -> Result<(), (u64, u64)> {
    if let Err(e) = std::str::from_utf8(bytes) {
        return Err(position_of(bytes, e.valid_up_to()));
    }
    for triple in TurtleParser::new().for_slice(bytes) {
        let triple = triple.map_err(|e| {
            let start = e.location().start;
            (start.line + 1, start.column + 1)
        })?;
        store
            .insert(triple.as_ref().in_graph(graph))
            .expect("inserting into the in-memory store");
    }
    Ok(())
}

/// The 1-based line and column (in code points) of a byte offset into `bytes`.
fn position_of(bytes: &[u8], offset: usize) -> (u64, u64) {
    let before = String::from_utf8_lossy(&bytes[..offset]);
    let line = before.matches('\n').count() as u64 + 1;
    let column = before.rsplit('\n').next().unwrap_or("").chars().count() as u64 + 1;
    (line, column)
}

/// Serializes one file's graph as deterministic Turtle (spec §3.4): the header line, the fixed
/// prefix table, then the triples sorted by subject, predicate and object (N-Triples forms),
/// with `rdf:type` first per subject.
pub fn to_turtle(store: &Store, file: File) -> String {
    let graph = file.graph();
    let mut triples: Vec<Triple> = store
        .quads_for_pattern(None, None, None, Some(graph.as_ref().into()))
        .map(|q| Triple::from(q.expect("reading the in-memory store")))
        .collect();
    triples.sort_by_cached_key(|t| {
        (
            t.subject.to_string(),
            t.predicate != rdf::TYPE,
            t.predicate.to_string(),
            t.object.to_string(),
        )
    });

    // oxttl orders its prefix lines by namespace length, so hali writes the prelude itself
    // and keeps the serializer's prefixes only for abbreviation.
    let mut serializer = TurtleSerializer::new();
    for (name, iri) in PREFIXES {
        serializer = serializer
            .with_prefix(name, iri)
            .expect("the prefix table is valid");
    }
    let mut writer = serializer.for_writer(Vec::new());
    for triple in &triples {
        writer
            .serialize_triple(triple)
            .expect("writing to memory cannot fail");
    }
    let body = String::from_utf8(writer.finish().expect("writing to memory cannot fail"))
        .expect("oxttl writes UTF-8");
    let prelude_lines = if triples.is_empty() {
        0
    } else {
        PREFIXES.len()
    };
    let body: String = body
        .split_inclusive('\n')
        .skip(prelude_lines)
        .collect::<String>();

    let mut out = String::from(HEADER);
    for (name, iri) in PREFIXES {
        out.push_str(&format!("@prefix {name}: <{iri}> .\n"));
    }
    out.push('\n');
    out.push_str(&body);
    out
}

/// Writes one file's graph into `dir`, creating `dir` (mode 0700) if needed.
pub fn save(dir: &Path, store: &Store, file: File) -> Result<(), Error> {
    fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(dir)
        .map_err(|_| Error::Io {
            path: dir.to_path_buf(),
        })?;
    let path = dir.join(file.name());
    fs::write(&path, to_turtle(store, file)).map_err(|_| Error::Io { path })
}

/// Reads a text file, if it exists.
pub fn read_text(path: &Path) -> Result<Option<String>, Error> {
    match fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(e) if e.kind() == ErrorKind::NotFound => Ok(None),
        Err(_) => Err(Error::Io {
            path: path.to_path_buf(),
        }),
    }
}

/// What `inspect` learns about a file to catalog, all from one open file descriptor.
#[derive(Debug)]
pub struct Inspected {
    pub byte_size: u64,
    /// The mtime, in whole seconds since the Unix epoch.
    pub mtime: i64,
    /// The SHA-256 of the content, lowercase hex.
    pub sha256: String,
    /// The first bytes of the content (at most `media_type::HEAD_LEN`).
    pub head: Vec<u8>,
}

/// Why a file cannot be cataloged.
#[derive(Debug, PartialEq)]
pub enum InspectError {
    Missing,
    Directory,
    /// Neither a regular file nor a directory: a FIFO, socket, device or symlink.
    Other,
    /// It exists but cannot be opened or read.
    Unreadable,
}

/// Opens the regular file at the real path `path` once, read-only and non-blocking, checks on
/// that descriptor that it is still a regular file, then hashes it by streaming. Nothing is
/// ever written to it.
pub fn inspect(path: &Path) -> Result<Inspected, InspectError> {
    use sha2::{Digest, Sha256};
    use std::io::Read;
    use std::os::unix::fs::{MetadataExt, OpenOptionsExt};

    // A first look without opening, so a device or FIFO is never opened.
    kind(fs::symlink_metadata(path))?;
    // O_NONBLOCK: a FIFO swapped in after that look cannot block the open. O_NOFOLLOW: nor can a
    // symlink be followed. O_NOCTTY: a terminal never becomes the controlling one.
    let mut file = fs::OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NONBLOCK | libc::O_NOFOLLOW | libc::O_NOCTTY)
        .open(path)
        .map_err(|e| match e.kind() {
            ErrorKind::NotFound => InspectError::Missing,
            _ => InspectError::Unreadable,
        })?;
    let meta = kind(file.metadata())?;

    let mut hasher = Sha256::new();
    let mut head = Vec::new();
    let mut buf = vec![0u8; 64 * 1024];
    let mut byte_size = 0u64;
    loop {
        let n = match file.read(&mut buf) {
            Ok(0) => break,
            Ok(n) => n,
            Err(e) if e.kind() == ErrorKind::Interrupted => continue,
            Err(_) => return Err(InspectError::Unreadable),
        };
        hasher.update(&buf[..n]);
        let room = crate::media_type::HEAD_LEN.saturating_sub(head.len());
        head.extend_from_slice(&buf[..n.min(room)]);
        byte_size += n as u64;
    }
    let sha256 = hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    Ok(Inspected {
        byte_size,
        mtime: meta.mtime(),
        sha256,
        head,
    })
}

/// A regular file's metadata, or the kind of thing that is there instead.
fn kind(meta: std::io::Result<fs::Metadata>) -> Result<fs::Metadata, InspectError> {
    match meta {
        Ok(m) if m.is_file() => Ok(m),
        Ok(m) if m.is_dir() => Err(InspectError::Directory),
        Ok(_) => Err(InspectError::Other),
        Err(e) if e.kind() == ErrorKind::NotFound => Err(InspectError::Missing),
        Err(_) => Err(InspectError::Unreadable),
    }
}

/// The size and mtime (whole seconds since the Unix epoch) of the regular file at `path`, from
/// `stat` only; `None` if there is no regular file there.
pub fn stat(path: &Path) -> Option<(u64, i64)> {
    use std::os::unix::fs::MetadataExt;
    fs::metadata(path)
        .ok()
        .filter(fs::Metadata::is_file)
        .map(|m| (m.len(), m.mtime()))
}
